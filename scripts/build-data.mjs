// Generates docs/workflows-data.js (+ docs/workflows/*.json copies for the Download links).
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { META, ORDER } from './workflow-meta.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export function buildDataSource() {
  const items = ORDER.map((file) => {
    const workflow = JSON.parse(readFileSync(join(root, 'workflows', file), 'utf8'));
    return { id: file.replace(/\.json$/, ''), file, ...META[file], workflow };
  });
  return '// GENERATED by scripts/build-data.mjs - do not edit.\nwindow.N8N_WORKFLOWS = ' + JSON.stringify(items, null, 1) + ';\n';
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = readdirSync(join(root, 'workflows')).filter((f) => f.endsWith('.json'));
  mkdirSync(join(root, 'docs/workflows'), { recursive: true });
  for (const f of files) copyFileSync(join(root, 'workflows', f), join(root, 'docs/workflows', f));
  writeFileSync(join(root, 'docs/workflows-data.js'), buildDataSource());
  console.log(`built docs/workflows-data.js (${files.length} workflows)`);
}
